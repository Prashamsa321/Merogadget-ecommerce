import mongoose from 'mongoose'

const productSchema = new mongoose.Schema({
  _id: {
    type: String,   
  },
  name: {
    type: String,
    required: true,
    trim: true
  },
  description: {
    type: String,
    required: true
  },
  price: {
    type: Number,
    required: true,
    min: 0
  },
  category: {
    type: String,
    required: true
  },
  image: {
    type: String,
    default: ''
  },
  images: [{
    type: String
  }],
  stock: {
    type: Number,
    required: true,
    default: 0,
    min: 0
  },
  createdAt: {
    type: Date,
    default: Date.now
  }
}, { _id: false, strict: false })  

const Product = mongoose.models.Product || mongoose.model('Product', productSchema)
export default Product